import Foundation
import SimulatorServices

/// What the project declares, read from `xcodebuild -showBuildSettings -json` and the files it names.
public struct ProjectSettings {
    static var applicationProductType: String {
        "com.apple.product-type.application"
    }

    static var storeKitMarker: String {
        "StoreKitConfigurationFileReference"
    }

    /// The union of what the application targets declare, plus StoreKit when a scheme file holds a configuration reference.
    ///
    /// Only targets whose `PRODUCT_TYPE` is an application count, and none of them is readable and declares nothing. A file the settings name that is missing, or does not parse, makes the whole read unreadable.
    public static func declarations(inBuildSettings data: Data, schemeFiles: [URL]) -> Result<ProjectDeclarations, UnreadableDeclarations> {
        let entries: [Entry]
        do {
            entries = try JSONDecoder().decode([Entry].self, from: data)
        } catch {
            return .failure(UnreadableDeclarations("build settings did not decode: \(error)"))
        }
        var merged = ProjectDeclarations()
        for settings in entries.map(\.buildSettings) where settings["PRODUCT_TYPE"] == applicationProductType {
            switch declarations(of: settings) {
            case let .success(found):
                merged.entitlements.formUnion(found.entitlements)
                merged.infoPlistKeys.formUnion(found.infoPlistKeys)
                merged.backgroundModes.formUnion(found.backgroundModes)
            case let .failure(failure):
                return .failure(failure)
            }
        }
        merged.storeKitConfiguration = schemeFiles.contains { url in
            (try? String(contentsOf: url, encoding: .utf8))?.contains(storeKitMarker) == true
        }
        return .success(merged)
    }

    /// The scheme files to look in: the container's shared scheme, then each application target's own project's.
    ///
    /// A file that does not exist is not an error here or in the read, since an autogenerated scheme carries no StoreKit configuration.
    public static func schemeFiles(container: TestInvocation.Container?, scheme: String, inBuildSettings data: Data) -> [URL] {
        var files: [URL] = []
        switch container {
        case let .project(path), let .workspace(path):
            files.append(schemeFile(in: URL(fileURLWithPath: path), scheme: scheme))
        case nil:
            break
        }
        let entries = (try? JSONDecoder().decode([Entry].self, from: data)) ?? []
        for settings in entries.map(\.buildSettings) where settings["PRODUCT_TYPE"] == applicationProductType {
            if let project = settings["PROJECT_FILE_PATH"], !project.isEmpty {
                let file = schemeFile(in: URL(fileURLWithPath: project), scheme: scheme)
                if !files.contains(file) {
                    files.append(file)
                }
            }
        }
        return files
    }

    private static func schemeFile(in container: URL, scheme: String) -> URL {
        container.appendingPathComponent("xcshareddata/xcschemes/\(scheme).xcscheme")
    }

    private static func declarations(of settings: [String: String]) -> Result<ProjectDeclarations, UnreadableDeclarations> {
        var entitlements: URL?
        var infoPlist: URL?
        do {
            entitlements = try existingFile(settings["CODE_SIGN_ENTITLEMENTS"], settings: settings)
            infoPlist = try existingFile(settings["INFOPLIST_FILE"], settings: settings)
        } catch let failure as UnreadableDeclarations {
            return .failure(failure)
        } catch {
            return .failure(UnreadableDeclarations("\(error)"))
        }
        var found: ProjectDeclarations
        do {
            found = try ProjectDeclarations.read(entitlements: entitlements, infoPlist: infoPlist, storeKitConfiguration: false)
        } catch {
            let named = [settings["CODE_SIGN_ENTITLEMENTS"], settings["INFOPLIST_FILE"]].compactMap(\.self).joined(separator: ", ")
            return .failure(UnreadableDeclarations("\(named): \(error.localizedDescription)"))
        }
        let prefix = "INFOPLIST_KEY_"
        for name in settings.keys where name.hasPrefix(prefix) && name.count > prefix.count {
            found.infoPlistKeys.insert(String(name.dropFirst(prefix.count)))
        }
        return .success(found)
    }

    /// The file a setting names, resolved against `SRCROOT` when relative, or nil when the setting is absent or empty.
    private static func existingFile(_ written: String?, settings: [String: String]) throws -> URL? {
        guard let written, !written.isEmpty else { return nil }
        let root = settings["SRCROOT"]
        var path = written
        if let root {
            path = path.replacingOccurrences(of: "$(SRCROOT)", with: root).replacingOccurrences(of: "${SRCROOT}", with: root)
        }
        let url = if path.hasPrefix("/") {
            URL(fileURLWithPath: path)
        } else if let root {
            URL(fileURLWithPath: root).appendingPathComponent(path)
        } else {
            URL(fileURLWithPath: path)
        }
        guard FileManager.default.fileExists(atPath: url.path) else {
            throw UnreadableDeclarations("\(written): no such file")
        }
        return url
    }
}

private extension ProjectSettings {
    /// One entry of `-showBuildSettings -json`, keeping the settings whose values are strings.
    struct Entry: Decodable {
        let buildSettings: [String: String]

        init(from decoder: any Decoder) throws {
            let container = try decoder.container(keyedBy: CodingKeys.self)
            let raw = try container.decodeIfPresent([String: Setting].self, forKey: .buildSettings) ?? [:]
            buildSettings = raw.compactMapValues(\.text)
        }
    }

    /// A setting's value, which is text or something SwiftSure does not read.
    struct Setting: Decodable {
        let text: String?

        init(from decoder: any Decoder) throws {
            text = try? decoder.singleValueContainer().decode(String.self)
        }
    }
}

private extension ProjectSettings.Entry {
    enum CodingKeys: String, CodingKey { case buildSettings }
}
